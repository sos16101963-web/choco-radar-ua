export interface LandingStatsResult {
  makersCount: number;
  localCount: number;
  minPriceUah: number;
  maxPriceUah: number;
  matchingMakers: CraftMaker[];
  effectiveInitialCity: string;
}

export function computeLandingStats(
  categorySlug: Exclude<CategorySlug, 'all'>,
  regionFilterId?: string,
  fallbackMin = 150,
  fallbackMax = 900
): LandingStatsResult {
  const categoryMakers = MAKERS.filter((m) => m.categories.includes(categorySlug));
  const needle = (regionFilterId || '').toLowerCase();

  const localMakers = needle
    ? categoryMakers.filter(
        (m) =>
          (m.city || '').toLowerCase().includes(needle) ||
          (m.regionCity || '').toLowerCase().includes(needle)
      )
    : categoryMakers;

  const matchingProducts = PRODUCTS.filter((p) => p.category === categorySlug);
  const prices = matchingProducts.map((p) => p.priceUah).filter((v) => v > 0);

  const minPriceUah = prices.length > 0 ? Math.min(...prices) : fallbackMin;
  const rawMax = prices.length > 0 ? Math.max(...prices) : fallbackMax;
  const maxPriceUah = rawMax > minPriceUah ? rawMax : Math.max(fallbackMax, Math.round(minPriceUah * 1.45));

  const orderedMakers =
    localMakers.length > 0
      ? [...localMakers, ...categoryMakers.filter((m) => !localMakers.some((l) => l.id === m.id))]
      : categoryMakers;

  return {
    makersCount: categoryMakers.length,
    localCount: localMakers.length,
    minPriceUah,
    maxPriceUah,
    matchingMakers: orderedMakers,
    effectiveInitialCity: needle && localMakers.length > 0 ? regionFilterId! : 'all',
  };
}

